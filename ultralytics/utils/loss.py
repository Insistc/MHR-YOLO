def bbox_siou_loss(pred: torch.Tensor, target: torch.Tensor, eps: float = 1e-7, theta: float = 4.0) -> torch.Tensor:
    """SIoU loss for xyxy boxes."""
    px1, py1, px2, py2 = pred.unbind(-1)
    tx1, ty1, tx2, ty2 = target.unbind(-1)
    pw = (px2 - px1).clamp(min=eps)
    ph = (py2 - py1).clamp(min=eps)
    tw = (tx2 - tx1).clamp(min=eps)
    th = (ty2 - ty1).clamp(min=eps)
    pcx, pcy = (px1 + px2) / 2, (py1 + py2) / 2
    tcx, tcy = (tx1 + tx2) / 2, (ty1 + ty2) / 2

    ix1, iy1 = torch.max(px1, tx1), torch.max(py1, ty1)
    ix2, iy2 = torch.min(px2, tx2), torch.min(py2, ty2)
    inter = (ix2 - ix1).clamp(min=0) * (iy2 - iy1).clamp(min=0)
    union = pw * ph + tw * th - inter + eps
    iou = inter / union

    cx1, cy1 = torch.min(px1, tx1), torch.min(py1, ty1)
    cx2, cy2 = torch.max(px2, tx2), torch.max(py2, ty2)
    cw = (cx2 - cx1).clamp(min=eps)
    ch = (cy2 - cy1).clamp(min=eps)

    sigma = torch.sqrt((tcx - pcx) ** 2 + (tcy - pcy) ** 2 + eps)
    sin_alpha_1 = torch.abs(tcx - pcx) / sigma
    sin_alpha_2 = torch.abs(tcy - pcy) / sigma
    threshold = torch.sqrt(torch.tensor(2.0, device=pred.device, dtype=pred.dtype)) / 2
    sin_alpha = torch.where(sin_alpha_1 > threshold, sin_alpha_2, sin_alpha_1)
    angle_cost = torch.cos(torch.arcsin(sin_alpha) * 2 - torch.pi / 2)
    gamma = 2 - angle_cost

    rho_x = ((tcx - pcx) / cw) ** 2
    rho_y = ((tcy - pcy) / ch) ** 2
    distance_cost = 2 - torch.exp(-gamma * rho_x) - torch.exp(-gamma * rho_y)

    omega_w = torch.abs(pw - tw) / torch.max(pw, tw)
    omega_h = torch.abs(ph - th) / torch.max(ph, th)
    shape_cost = (1 - torch.exp(-omega_w)) ** theta + (1 - torch.exp(-omega_h)) ** theta
    return 1 - iou + (distance_cost + shape_cost) / 2


